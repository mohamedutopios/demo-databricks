-- =====================================================================
-- 04_gold.sql — Silver → Gold : modèle en étoile
--   Dimensions : dim_date, dim_canal, dim_magasin, dim_produit (SCD1), dim_client (SCD2 + membre inconnu)
--   Faits      : fact_ventes (grain : ligne de vente, ventes validées uniquement)
-- Ré-exécutable : oui (idempotent)
-- =====================================================================

USE CATALOG projet_medaillon;

-- =====================================================================
-- 1. DIMENSIONS — STRUCTURES
-- =====================================================================
CREATE TABLE IF NOT EXISTS gold.dim_date (
  date_key      INT     NOT NULL COMMENT 'AAAAMMJJ',
  date_jour     DATE    NOT NULL,
  annee         INT,
  trimestre     INT,
  mois          INT,
  mois_debut    DATE    COMMENT 'Premier jour du mois',
  nom_mois      STRING,
  semaine_iso   INT,
  jour_semaine  INT     COMMENT '1 = dimanche … 7 = samedi',
  nom_jour      STRING,
  est_weekend   BOOLEAN,
  CONSTRAINT pk_dim_date PRIMARY KEY (date_key) RELY
) COMMENT 'Gold : calendrier 2024-2030';

CREATE TABLE IF NOT EXISTS gold.dim_canal (
  canal_code  STRING NOT NULL,
  libelle     STRING,
  type_canal  STRING,
  CONSTRAINT pk_dim_canal PRIMARY KEY (canal_code) RELY
) COMMENT 'Gold : canaux de vente';

CREATE TABLE IF NOT EXISTS gold.dim_magasin (
  code_magasin  STRING NOT NULL,
  nom           STRING,
  ville         STRING,
  region        STRING,
  surface_m2    INT,
  CONSTRAINT pk_dim_magasin PRIMARY KEY (code_magasin) RELY
) COMMENT 'Gold : magasins (AUCUN = vente hors magasin)';

CREATE TABLE IF NOT EXISTS gold.dim_produit (
  sku             STRING NOT NULL,
  libelle         STRING,
  categorie       STRING,
  marque          STRING,
  prix_catalogue  DECIMAL(10,2),
  cout_achat      DECIMAL(10,2),
  actif           BOOLEAN,
  CONSTRAINT pk_dim_produit PRIMARY KEY (sku) RELY
) COMMENT 'Gold : produits (SCD type 1)';

CREATE TABLE IF NOT EXISTS gold.dim_client (
  client_sk       BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
  client_id       INT    NOT NULL COMMENT 'Clé métier ERP (-1 = membre inconnu)',
  nom_complet     STRING,
  email           STRING,
  ville           STRING,
  code_postal     STRING,
  segment         STRING,
  hash_attributs  STRING NOT NULL,
  date_debut      DATE   NOT NULL,
  date_fin        DATE,
  est_courant     BOOLEAN NOT NULL,
  CONSTRAINT pk_dim_client PRIMARY KEY (client_sk) RELY
) COMMENT 'Gold : clients historisés (SCD type 2), client_sk = -1 pour anonyme ou non référencé'
CLUSTER BY (client_id);

-- =====================================================================
-- 2. FAITS — STRUCTURE
-- =====================================================================
CREATE TABLE IF NOT EXISTS gold.fact_ventes (
  canal_code        STRING        NOT NULL,
  vente_id          STRING        NOT NULL,
  ligne_num         INT           NOT NULL,
  date_key          INT           NOT NULL,
  heure             INT,
  horodatage_vente  TIMESTAMP,
  client_sk         BIGINT        NOT NULL,
  sku               STRING        NOT NULL,
  code_magasin      STRING        NOT NULL,
  quantite          INT,
  prix_unitaire     DECIMAL(10,2),
  remise_pct        DECIMAL(5,2),
  montant_brut      DECIMAL(12,2),
  montant_net       DECIMAL(12,2),
  cout_total        DECIMAL(12,2),
  marge             DECIMAL(12,2),
  _maj_ts           TIMESTAMP,
  CONSTRAINT pk_fact_ventes PRIMARY KEY (canal_code, vente_id, ligne_num) RELY,
  CONSTRAINT fk_fv_date    FOREIGN KEY (date_key)     REFERENCES gold.dim_date,
  CONSTRAINT fk_fv_canal   FOREIGN KEY (canal_code)   REFERENCES gold.dim_canal,
  CONSTRAINT fk_fv_client  FOREIGN KEY (client_sk)    REFERENCES gold.dim_client,
  CONSTRAINT fk_fv_produit FOREIGN KEY (sku)          REFERENCES gold.dim_produit,
  CONSTRAINT fk_fv_magasin FOREIGN KEY (code_magasin) REFERENCES gold.dim_magasin
) COMMENT 'Gold : ventes validées, grain ligne de vente, 3 canaux'
CLUSTER BY (date_key);

-- =====================================================================
-- 3. VUES SOURCES
-- =====================================================================
CREATE OR REPLACE VIEW gold.v_client_source AS
SELECT
  client_id, nom_complet, email, ville, code_postal, segment,
  sha2(concat_ws('||', nom_complet, email, ville, code_postal, segment), 256) AS hash_attributs,
  CAST(date_maj AS DATE)                                                      AS date_effet
FROM silver.client;

-- Jointure "point-in-time" : chaque vente pointe sur la version du client valide à sa date
CREATE OR REPLACE VIEW gold.v_ventes_source AS
SELECT
  v.canal                                                           AS canal_code,
  v.vente_id,
  v.ligne_num,
  year(v.date_vente) * 10000 + month(v.date_vente) * 100 + day(v.date_vente) AS date_key,
  hour(v.horodatage_vente)                                          AS heure,
  v.horodatage_vente,
  coalesce(dc.client_sk, -1)                                        AS client_sk,
  v.sku,
  coalesce(v.code_magasin, 'AUCUN')                                 AS code_magasin,
  v.quantite,
  v.prix_unitaire,
  v.remise_pct,
  v.montant_brut,
  v.montant_net,
  CAST(v.quantite * p.cout_achat AS DECIMAL(12,2))                  AS cout_total,
  CAST(v.montant_net - v.quantite * p.cout_achat AS DECIMAL(12,2))  AS marge,
  v.statut
FROM silver.vente_ligne v
LEFT JOIN gold.dim_client dc
  ON  dc.client_id = v.client_id
  AND v.date_vente BETWEEN dc.date_debut AND coalesce(dc.date_fin, DATE'9999-12-31')
LEFT JOIN gold.dim_produit p
  ON  p.sku = v.sku;

-- =====================================================================
-- 4. CHARGEMENT DES DIMENSIONS
-- =====================================================================

-- 4.1 Calendrier
MERGE INTO gold.dim_date AS t
USING (
  SELECT
    year(d) * 10000 + month(d) * 100 + day(d)                                    AS date_key,
    d                                                                            AS date_jour,
    year(d)                                                                      AS annee,
    quarter(d)                                                                   AS trimestre,
    month(d)                                                                     AS mois,
    trunc(d, 'MM')                                                               AS mois_debut,
    element_at(array('janvier','février','mars','avril','mai','juin','juillet',
                     'août','septembre','octobre','novembre','décembre'), month(d)) AS nom_mois,
    weekofyear(d)                                                                AS semaine_iso,
    dayofweek(d)                                                                 AS jour_semaine,
    element_at(array('dimanche','lundi','mardi','mercredi','jeudi','vendredi','samedi'), dayofweek(d)) AS nom_jour,
    dayofweek(d) IN (1, 7)                                                       AS est_weekend
  FROM (SELECT explode(sequence(DATE'2024-01-01', DATE'2030-12-31', INTERVAL 1 DAY)) AS d)
) AS s
ON t.date_key = s.date_key
WHEN NOT MATCHED THEN INSERT *;

-- 4.2 Canaux (référentiel fixe)
MERGE INTO gold.dim_canal AS t
USING (
  SELECT * FROM VALUES
    ('ERP',     'Vente directe (ERP)', 'Direct'),
    ('MAGASIN', 'Magasins physiques',  'Physique'),
    ('WEB',     'Site e-commerce',     'Digital')
  AS v(canal_code, libelle, type_canal)
) AS s
ON t.canal_code = s.canal_code
WHEN MATCHED AND NOT (t.libelle <=> s.libelle AND t.type_canal <=> s.type_canal) THEN UPDATE SET *
WHEN NOT MATCHED THEN INSERT *;

-- 4.3 Magasins (+ membre "AUCUN" pour les ventes ERP et web)
MERGE INTO gold.dim_magasin AS t
USING (
  SELECT code_magasin, nom, ville, region, surface_m2 FROM silver.magasin
  UNION ALL
  SELECT 'AUCUN', 'Hors magasin', 'N/A', 'N/A', CAST(NULL AS INT)
) AS s
ON t.code_magasin = s.code_magasin
WHEN MATCHED AND NOT (t.nom <=> s.nom AND t.ville <=> s.ville AND t.region <=> s.region AND t.surface_m2 <=> s.surface_m2)
  THEN UPDATE SET *
WHEN NOT MATCHED THEN INSERT *;

-- 4.4 Produits (SCD type 1 : écrasement)
MERGE INTO gold.dim_produit AS t
USING (
  SELECT sku, libelle, categorie, marque, prix_catalogue, cout_achat, actif FROM silver.produit
) AS s
ON t.sku = s.sku
WHEN MATCHED AND NOT (    t.libelle <=> s.libelle AND t.categorie <=> s.categorie AND t.marque <=> s.marque
                      AND t.prix_catalogue <=> s.prix_catalogue AND t.cout_achat <=> s.cout_achat
                      AND t.actif <=> s.actif)
  THEN UPDATE SET *
WHEN NOT MATCHED THEN INSERT *;

-- 4.5 Client — membre inconnu (client_sk = -1)
MERGE INTO gold.dim_client AS t
USING (SELECT CAST(-1 AS BIGINT) AS client_sk) AS s
ON t.client_sk = s.client_sk
WHEN NOT MATCHED THEN
  INSERT (client_sk, client_id, nom_complet, email, ville, code_postal, segment,
          hash_attributs, date_debut, date_fin, est_courant)
  VALUES (-1, -1, 'Client anonyme ou non référencé', NULL, 'N/A', NULL, 'N/A',
          'membre_inconnu', DATE'1900-01-01', NULL, true);

-- 4.6 Client — SCD type 2
--   Branche 1 : chaque client, rattaché à sa version courante par clé métier
--               → si attributs modifiés : clôture de la version courante (veille de la date d'effet)
--               → si client nouveau     : insertion, version valide depuis 1900-01-01
--   Branche 2 : clients modifiés, clé de fusion NULL → insertion de la nouvelle version (depuis la date d'effet)
MERGE INTO gold.dim_client AS t
USING (
  SELECT s.client_id AS cle_fusion, s.*
  FROM gold.v_client_source s
  UNION ALL
  SELECT NULL AS cle_fusion, s.*
  FROM gold.v_client_source s
  JOIN gold.dim_client d
    ON d.client_id = s.client_id
   AND d.est_courant
  WHERE d.hash_attributs <> s.hash_attributs
) AS s
ON t.client_id = s.cle_fusion AND t.est_courant
WHEN MATCHED AND t.hash_attributs <> s.hash_attributs THEN
  UPDATE SET est_courant = false,
             date_fin    = date_sub(s.date_effet, 1)
WHEN NOT MATCHED THEN
  INSERT (client_id, nom_complet, email, ville, code_postal, segment,
          hash_attributs, date_debut, date_fin, est_courant)
  VALUES (s.client_id, s.nom_complet, s.email, s.ville, s.code_postal, s.segment,
          s.hash_attributs,
          CASE WHEN s.cle_fusion IS NULL THEN s.date_effet ELSE DATE'1900-01-01' END,
          NULL, true);

-- =====================================================================
-- 5. CHARGEMENT DES FAITS
--    Nouvelle vente validée → insertion | vente modifiée → mise à jour | vente annulée → suppression
-- =====================================================================
MERGE INTO gold.fact_ventes AS t
USING gold.v_ventes_source AS s
ON t.canal_code = s.canal_code AND t.vente_id = s.vente_id AND t.ligne_num = s.ligne_num
WHEN MATCHED AND s.statut = 'ANNULEE' THEN
  DELETE
WHEN MATCHED AND NOT (    t.client_sk     <=> s.client_sk
                      AND t.date_key      <=> s.date_key
                      AND t.quantite      <=> s.quantite
                      AND t.prix_unitaire <=> s.prix_unitaire
                      AND t.remise_pct    <=> s.remise_pct
                      AND t.cout_total    <=> s.cout_total) THEN
  UPDATE SET date_key         = s.date_key,
             heure            = s.heure,
             horodatage_vente = s.horodatage_vente,
             client_sk        = s.client_sk,
             sku              = s.sku,
             code_magasin     = s.code_magasin,
             quantite         = s.quantite,
             prix_unitaire    = s.prix_unitaire,
             remise_pct       = s.remise_pct,
             montant_brut     = s.montant_brut,
             montant_net      = s.montant_net,
             cout_total       = s.cout_total,
             marge            = s.marge,
             _maj_ts          = current_timestamp()
WHEN NOT MATCHED AND s.statut = 'VALIDEE' THEN
  INSERT (canal_code, vente_id, ligne_num, date_key, heure, horodatage_vente, client_sk, sku, code_magasin,
          quantite, prix_unitaire, remise_pct, montant_brut, montant_net, cout_total, marge, _maj_ts)
  VALUES (s.canal_code, s.vente_id, s.ligne_num, s.date_key, s.heure, s.horodatage_vente, s.client_sk, s.sku,
          s.code_magasin, s.quantite, s.prix_unitaire, s.remise_pct, s.montant_brut, s.montant_net,
          s.cout_total, s.marge, current_timestamp());

-- =====================================================================
-- 6. CONTRÔLE RAPIDE
-- =====================================================================
SELECT f.canal_code, count(*) AS lignes, sum(f.montant_net) AS ca_net,
       count_if(f.client_sk = -1) AS lignes_client_inconnu
FROM gold.fact_ventes f
GROUP BY ALL
ORDER BY f.canal_code;
